<?php

namespace Webkul\Customer\Helpers;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;
use Webkul\Checkout\Repositories\CartRepository;
use Webkul\Customer\Repositories\CreditAccountRepository;
use Webkul\Sales\Repositories\InvoiceRepository;
use Webkul\Sales\Repositories\OrderRepository;
use Webkul\Sales\Transformers\OrderResource;
use Webkul\Shop\Listeners\Order;

class CreditSplitCheckout
{
    public static function gatewayAvailable(): bool
    {
        $class = config('payment_methods.zarinpal.class');

        return $class && (bool) app($class)->isAvailable();
    }

    public function reserve($cart)
    {
        return DB::transaction(function () use ($cart) {
            $cart = app(CartRepository::class)->getModel()->newQuery()->lockForUpdate()->findOrFail($cart->id);
            $customer = auth()->guard('customer')->user();
            if (! $customer || $cart->customer_id !== $customer->id || ! $cart->is_active || $cart->payment?->method !== 'customer_credit' || ! self::gatewayAvailable()) {
                $this->fail();
            }
            $data = (new OrderResource($cart))->jsonSerialize();
            $data['payment']['additional'] = null;
            $hash = hash('sha256', json_encode($data, JSON_THROW_ON_ERROR));
            $orders = app(OrderRepository::class);
            $existing = $orders->getModel()->newQuery()->where('cart_id', $cart->id)->where('status', '!=', 'canceled')->latest('id')->first();
            if ($existing) {
                if (! data_get($existing->payment->additional, 'credit_split')) {
                    $this->fail();
                }

                if (data_get($existing->payment->additional, 'credit_split.cart_hash') === $hash) {
                    return $existing;
                }
                $this->cancel($existing->id);
            }
            $accounts = app(CreditAccountRepository::class);
            $account = $accounts->forCustomer($customer);
            if (! $account) {
                $this->fail();
            }
            $account = $accounts->getModel()->newQuery()->lockForUpdate()->findOrFail($account->id);
            $factor = CreditIdentity::orderRial(1, $cart->base_currency_code);
            $total = (int) round((float) $cart->base_grand_total);
            $credit = intdiv($accounts->availableBalance($account, null, true), $factor);
            if (! $account->is_active || $credit < 1 || $credit >= $total) {
                $this->fail();
            }
            // This metadata is always generated by the server, never from orderData.
            $data['payment']['additional'] = ['credit_split' => [
                'credit_rial' => $credit * $factor, 'gateway_amount' => $total - $credit,
                'cart_hash' => $hash, 'gateway' => 'zarinpal', 'state' => 'pending', 'token' => (string) Str::uuid(),
                'expires_at' => now()->addMinutes(30)->toDateTimeString(),
            ]];

            $order = $orders->create($data);
            $cart->update(['is_active' => false]);

            return $order;
        }, 3);
    }

    public function complete(int $id, string $authority, callable $verify)
    {
        return DB::transaction(function () use ($id, $authority, $verify) {
            $order = app(OrderRepository::class)->getModel()->newQuery()->lockForUpdate()->findOrFail($id);
            $split = $order->payment->additional['credit_split'] ?? [];
            if (($split['authority'] ?? '') !== $authority || $order->status === 'canceled') {
                $this->fail();
            }
            if (($split['state'] ?? '') === 'paid') {
                return $order;
            }
            $result = $verify($split);
            if (! in_array((int) data_get($result, 'data.code'), [100, 101], true)) {
                $this->fail();
            }
            app(CreditAccountRepository::class)->settleSplitOrder($order);
            $split['state'] = 'paid';
            $split['ref_id'] = (string) data_get($result, 'data.ref_id', $authority);
            $order->payment->update(['additional' => ['credit_split' => $split]]);
            $items = $order->items->mapWithKeys(fn ($item) => [$item->id => $item->qty_to_invoice])->filter()->all();
            if ($items && ! $order->invoices()->exists()) {
                app(InvoiceRepository::class)->create(['order_id' => $order->id, 'invoice' => ['items' => $items]], 'paid');
            }
            app(OrderRepository::class)->update(['status' => 'processing'], $order->id);
            app(CartRepository::class)->update(['is_active' => false], $order->cart_id);
            app(Order::class)->afterCreated($order->fresh());

            return $order->fresh();
        }, 3);
    }

    public function cancel(int $id): void
    {
        DB::transaction(function () use ($id) {
            $orders = app(OrderRepository::class);
            $order = $orders->getModel()->newQuery()->lockForUpdate()->findOrFail($id);
            $split = $order->payment->additional['credit_split'] ?? [];
            if (($split['state'] ?? '') !== 'pending') {
                return;
            }
            if ($order->status !== 'canceled' && ! $orders->cancel($order)) {
                $this->fail();
            }
            app(CreditAccountRepository::class)->returnOrderCredit($order, PHP_INT_MAX, 'order:'.$id.':cancel', 'cancel');
            app(CartRepository::class)->update(['is_active' => true], $order->cart_id);
            $split['state'] = 'canceled';
            $order->payment->update(['additional' => ['credit_split' => $split]]);
        }, 3);
    }

    private function fail(): never
    {
        throw ValidationException::withMessages(['credit' => trans('customer::credit.splitFailed')]);
    }
}
